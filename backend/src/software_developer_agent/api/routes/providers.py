@router.post("/supabase/projects/{project_ref}/secrets", status_code=201)
def create_supabase_secrets(
    project_ref: str,
    payload: SupabaseSecretsRequest,
) -> dict[str, Any]:
    try:
        return SupabaseProvider(get_settings()).create_secrets(
            project_ref,
            {name: value.get_secret_value() for name, value in payload.secrets.items()},
            confirm_write=payload.confirm_write,
        )
    except ProviderError as exc:
        raise HTTPException(status_code=exc.status_code, detail=str(exc)) from exc
